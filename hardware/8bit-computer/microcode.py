#!/usr/bin/env python3
"""
Generate the control-logic EEPROM image (28C16, 2 KB) from isa.py.

    python3 microcode.py          ->  build/microcode.bin   (raw image)
                                      arduino/eeprom_programmer/microcode.h
                                      prints the microcode table

Both control EEPROMs get the SAME image. What makes them different is how
address line A7 is wired: tied LOW on the left chip, HIGH on the right
one. A7 selects which half of the 16-bit control word a chip outputs, so
one image serves both.

EEPROM address lines (who drives them):

    A10        A9     A8     A7          A6 A5 A4 A3       A2 A1 A0
    unused(0)  ZF     CF     chip select  opcode (IR 7..4)  step (T0..T4)
               '-- flags --'              '- instruction -'  '- step counter -'

So the control word the chips output is a pure lookup:
    f(flags, opcode, step) -> 16 control bits
"""
import sys
from pathlib import Path

from isa import STEPS, INSTRUCTIONS, describe, micro_steps

SIZE = 2048


def address(flags: int, chip_low: int, opcode: int, step: int) -> int:
    return (flags << 8) | (chip_low << 7) | (opcode << 3) | step


def build_image() -> bytes:
    image = bytearray(SIZE)
    for flags in range(4):
        for opcode in range(16):
            words = micro_steps(opcode, flags)
            for step in range(8):                  # steps 5..7 never happen: leave them 0
                word = words[step] if step < STEPS else 0
                image[address(flags, 0, opcode, step)] = word >> 8     # left chip: bits 15..8
                image[address(flags, 1, opcode, step)] = word & 0xFF   # right chip: bits 7..0
    return bytes(image)


def c_header(image: bytes, name: str) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in image[i:i + 16]) for i in range(0, len(image), 16)]
    body = ",\n  ".join(rows)
    return (f"// Generated by {Path(sys.argv[0]).name} - do not edit by hand.\n"
            f"#include <avr/pgmspace.h>\n"
            f"const unsigned int IMAGE_SIZE = {len(image)};\n"
            f"const char IMAGE_NAME[] = \"{name}\";\n"
            f"const byte IMAGE[] PROGMEM = {{\n  {body}\n}};\n")


def print_table():
    print("op    name  flags  T0          T1            T2          T3          T4")
    for opcode, (name, _, _) in sorted(INSTRUCTIONS.items()):
        for flags in range(4):
            if name not in ("JC", "JZ") and flags:
                continue                           # identical for every flag value
            steps = "  ".join(f"{describe(w):<11}" for w in micro_steps(opcode, flags))
            print(f"{opcode:04b}  {name:<4}  {flags:02b}     {steps}")


def main():
    out = Path(__file__).parent / "build"
    out.mkdir(exist_ok=True)
    image = build_image()
    (out / "microcode.bin").write_bytes(image)
    sketch = Path(__file__).parent / "arduino" / "eeprom_programmer"
    (sketch / "microcode.h").write_text(c_header(image, "microcode"))
    print_table()
    print(f"\nwrote build/microcode.bin and arduino/eeprom_programmer/microcode.h ({len(image)} bytes)")


if __name__ == "__main__":
    main()
